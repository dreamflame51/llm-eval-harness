"""Render docs/traceability.md from eval/traceability.yaml.

Run:  uv run python scripts/traceability.py

One source, two readers: the document a person opens and the panel on the
readout page. Neither is edited by hand, because a matrix maintained in two
places is a matrix that disagrees with itself within a month.

What keeps it honest is not this script - it is
tests/eval/test_traceability.py, which checks every test id against the
collected suite and every evidence path against the repository. This only
formats what that has already validated.
"""

import pathlib

import yaml

MATRIX = pathlib.Path("eval/traceability.yaml")
NEEDS = pathlib.Path("eval/needs.yaml")
OUT = pathlib.Path("docs/traceability.md")
V_MODEL = pathlib.Path("eval/v_model.yaml")
V_DOC = pathlib.Path("docs/v-model.md")
V_DOC_RU = pathlib.Path("docs/v-model.ru.md")
V_START = "<!-- levels:start"
V_END = "<!-- levels:end -->"

HEADER = """\
# Traceability

What this harness claims about the system, what verifies each claim, and where
the evidence sits. Generated from [`eval/traceability.yaml`](../eval/traceability.yaml)
by `scripts/traceability.py`; do not edit this file.

Every test named here is checked against the collected suite and every evidence
path against the repository by `tests/eval/test_traceability.py`, so a reference
that has rotted fails the build instead of quietly making this page look
complete.

**held as** says how the claim is enforced:

- **gate** - a test fails and the build is red.
- **measurement** - a number is produced and read by a person. Most of these
  are measurements on purpose: no acceptance threshold has been agreed for any
  metric in this project, and a threshold invented to keep a dashboard green
  would be worse than none.
"""


def render_needs(needs, entries):
    """The level above the requirements, and what serves each one."""
    by_id = {entry["id"]: entry for entry in entries}
    lines = ["\n## What this is for\n"]
    lines.append(
        "Written last. For most of this project's life this level did not exist and "
        "every requirement below traced upward to nothing; see "
        "[v-model.md](v-model.md), GAP-4. These say what a person wants from the "
        "system, not what the harness can tell.\n"
    )
    for need in needs:
        lines.append(f"**{need['id']}** &mdash; {' '.join(need['need'].split())}\n")
        served = ", ".join(
            f"{req} ({by_id[req]['measured']})" for req in need["served_by"] if req in by_id
        )
        lines.append(f"Served by {served}.\n")
    return "\n".join(lines)


def render(entries, needs):
    lines = [HEADER, render_needs(needs, entries)]
    lines.append(f"\n{len(entries)} requirements, "
                 f"{sum(len(e['tests']) for e in entries)} test references, "
                 f"{sum(1 for e in entries if e['measured'] == 'gate')} held as gates.\n")

    lines.append("| id | requirement | held as | lesson |")
    lines.append("|---|---|---|---|")
    for entry in entries:
        lesson = entry.get("lesson", "")
        link = f"[{lesson.rsplit('#', 1)[-1]}]({lesson.replace('docs/', '')})" if lesson else ""
        lines.append(
            f"| {entry['id']} | {' '.join(entry['requirement'].split())} "
            f"| {entry['measured']} | {link} |"
        )

    for entry in entries:
        lines.append(f"\n## {entry['id']}\n")
        lines.append(" ".join(entry["requirement"].split()) + "\n")
        lines.append(f"**Held as** {entry['measured']}.\n")
        lines.append("**Verified by**\n")
        for test in entry["tests"]:
            lines.append(f"- `{test}`")
        lines.append("\n**Run**\n")
        for check in entry["checks"]:
            lines.append(f"- `{check}`")
        lines.append("\n**Evidence**\n")
        for path in entry["evidence"]:
            lines.append(f"- [`{path}`](../{path})")
    return "\n".join(lines) + "\n"


# The header row and the words for each state, per language. Only these
# differ between the two documents - the rows themselves are the same data.
V_HEADINGS = {
    V_DOC: (
        ["| level | specified where | verified by | state |", "|---|---|---|---|"],
        {"present": "present", "partial": "partial", "missing": "missing"},
    ),
    V_DOC_RU: (
        ["| уровень | где задан | чем проверяется | состояние |", "|---|---|---|---|"],
        {"present": "есть", "partial": "частично", "missing": "нет"},
    ),
}


def render_levels(levels, doc):
    """The V-model table, for the block inside one of the v-model documents."""
    header, words = V_HEADINGS[doc]
    lines = list(header)
    for level in levels:
        state = words[level["state"]]
        shown = state if level["state"] == "present" else f"**{state}**"
        lines.append(
            f"| {level['level']} | {level['specified']} | {level['verified']} | {shown} |"
        )
    return "\n".join(lines)


def update_v_model(levels):
    """
    Replace the generated table in both v-model documents, prose untouched.

    The documents argue; this table is data. Keeping the data in
    eval/v_model.yaml means the panel on the readout page and the tables here
    cannot disagree - and neither can the two languages, which is the failure
    mode of every second translated document.
    """
    for doc in (V_DOC, V_DOC_RU):
        if not doc.exists():
            continue
        body = doc.read_text(encoding="utf-8")
        start = body.index(V_START)
        start = body.index("\n", start) + 1
        end = body.index(V_END)
        doc.write_text(
            body[:start] + render_levels(levels, doc) + "\n" + body[end:], encoding="utf-8"
        )


def main():
    entries = yaml.safe_load(MATRIX.read_text(encoding="utf-8"))
    needs = yaml.safe_load(NEEDS.read_text(encoding="utf-8"))
    OUT.write_text(render(entries, needs), encoding="utf-8")
    gates = sum(1 for entry in entries if entry["measured"] == "gate")
    print(f"wrote {OUT}: {len(needs)} user needs, {len(entries)} requirements, "
          f"{gates} gates, {len(entries) - gates} measurements")

    v_model = yaml.safe_load(V_MODEL.read_text(encoding="utf-8"))
    update_v_model(v_model["levels"])
    missing = sum(1 for level in v_model["levels"] if level["state"] != "present")
    print(f"wrote {V_DOC}: {len(v_model['levels'])} levels, {missing} not fully present, "
          f"{len(v_model['gaps'])} gaps")


if __name__ == "__main__":
    main()
