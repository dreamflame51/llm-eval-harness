"""Record the generator's answers to the refusal questions, once, into a file.

Run:  uv run python scripts/record_answers.py [--force]

Generation is reproducible inside one process and not between processes: the
same question, against the same five retrieved chunks with the same distances,
comes back worded differently after the model is reloaded (docs/lessons.md #17).
That is tolerable for a headline metric, which is allowed to be a sample of a
drifting system. It is not tolerable underneath a hand-labelled set: labels are
attached to a specific answer, and if the answer changes, the labels describe
text that no longer exists and the judge's cached verdicts all miss.

So the answers are frozen here. What this file records stops being an output of
the system and becomes an input to the measurement - the same status the gold
contexts in ground_truth.yaml already have.

It records the retrieved chunks too, in full. Retrieval is deterministic today,
but only against this index: rebuild it at a different chunk size and the same
question returns different text. Storing what the model actually saw makes the
labelled set self-contained - it can be read, labelled, and judged with neither
Ollama nor Chroma running.

The file is hand-edited afterwards, so this script will not overwrite it. Pass
--force only when you mean to discard the labels in it.
"""

import argparse
import datetime
import pathlib

import yaml

from llm_eval_harness import chunker, pipeline, store
from llm_eval_harness.dataset import answerable_records, refusal_records

OUT = pathlib.Path("eval/refusal_answers.yaml")
ANSWERABLE_OUT = pathlib.Path("eval/answerable_answers.yaml")


class Dumper(yaml.SafeDumper):
    """Keeps multi-line strings readable - these get read by a human."""


def _str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, _str)


HEADER = """\
# Recorded answers to the refusal questions - the hand-labelling set.
#
# Generated by scripts/record_answers.py. Do not regenerate to "refresh" it:
# the point is that it does NOT move. The generator drifts between processes
# (docs/lessons.md #17), so a re-run produces different text and silently
# invalidates every label below.
#
# Provenance of this snapshot:
#   recorded:        {recorded}
#   generator:       {model}, options {options}
#   retrieval:       {retriever}, k={k}, {embedder}
#   chunking:        {size}/{overlap}
#
# The retriever is named here because leaving it out cost a day: this block
# read the same before and after BM25 was fused into retrieval, so a set
# recorded under dense retrieval went on being scored as though it described
# the running system (docs/lessons.md #25).
#
# Fill in by hand, one record at a time, two independent questions:
#
#   refused     did the answer decline to answer from the corpus?
#               A sentence that names what is missing counts ("the context does
#               not state a minimum"). An answer that hedges and then answers
#               anyway does NOT count as a refusal.
#   fabricated  does the answer assert anything about the question that the
#               retrieved chunks below do not support? Judge against those
#               chunks only - not against what you know to be true of the
#               standard. Content correctly drawn from the corpus is not
#               fabricated, even when the question asked about an absent
#               document.
#
# The two are independent, and the combination that matters most is
# refused=true with fabricated=true: declined, then invented anyway. The phrase
# list in refusal.py cannot see that case at all, which is why this set exists.
#
# Leave note free-form; it is where a case that resists both flags gets
# described.
"""

ANSWERABLE_HEADER = """\
# Recorded answers to the 26 answerable questions - the generation-side set.
#
# Generated by scripts/record_answers.py --set answerable. Frozen for the same
# reason as the refusal answers: the generator drifts between processes
# (docs/lessons.md #17), and a RAGAS or DeepEval run that costs an hour must
# not be scoring text that changed since the last one.
#
# Provenance of this snapshot:
#   recorded:        {recorded}
#   generator:       {model}, options {options}
#   retrieval:       {retriever}, k={k}, {embedder}
#   chunking:        {size}/{overlap}
#
#   question         what was asked
#   answer           what the generator said, from the chunks below
#   reference        the gold answer from eval/ground_truth.yaml
#   gold_contexts    the spans that support the gold answer
#   retrieved        what retrieval actually served, in rank order
#
# Nothing here is hand-labelled. The reference and the gold contexts come from
# ground_truth.yaml, which validate.py already checks against the corpus.
"""


def build(records, refusal=True):
    rows = []
    for i, rec in enumerate(records, 1):
        result = pipeline.answer(rec["question"])
        print(f"  {i}/{len(records)}  {rec['question'][:64]}", flush=True)
        row = {
            "question": rec["question"],
            "source": rec.get("source"),
            "answer": result["answer"].strip(),
        }
        if refusal:
            row["refusal_type"] = rec.get("refusal_type")
            row["topic_in_corpus"] = rec.get("topic_in_corpus")
            row["labels"] = {"refused": None, "fabricated": None, "note": ""}
        else:
            # The gold answer and the gold spans travel with the recorded one:
            # RAGAS scores a response against a reference, and the reference
            # has to be the same text the retrieval metrics already use or the
            # two halves of the harness stop describing the same fixture.
            row["reference"] = rec["answer"]
            row["gold_contexts"] = list(rec["contexts"])
        row["retrieved"] = [
            {
                "source": c["source"],
                # None when only BM25 ranked this chunk: it has no distance in
                # the embedding space, and rounding a missing number is how
                # this script crashed the first time the retriever changed.
                "distance": None if c.get("distance") is None else round(c["distance"], 4),
                "text": c["text"],
            }
            for c in result["contexts"]
        ]
        rows.append(row)
    return rows


def carry_labels(rows, old_path):
    """
    Move hand labels onto the new recording, but only where nothing moved.

    A label is a judgement about one answer against the chunks that answer was
    written from. Carrying it to different text would not be preserving work,
    it would be attaching a verdict to something nobody read. So a label
    travels only when the new answer and all of its chunks are identical to
    the ones it was written about, character for character.

    Returns (kept, stale) as lists of questions. In practice `stale` is most
    of them - the generator drifts between processes even with identical
    retrieval (docs/lessons.md #17) - and that is the point: the number says
    how much re-labelling a change really costs, instead of leaving it to be
    guessed at.
    """
    if not old_path.exists():
        return [], [row["question"] for row in rows]

    previous = {}
    for row in yaml.safe_load(old_path.read_text(encoding="utf-8")) or []:
        previous[row["question"]] = row

    kept, stale = [], []
    for row in rows:
        old = previous.get(row["question"])
        same = (
            old is not None
            and old.get("answer", "").strip() == row["answer"]
            and [c["text"] for c in old.get("retrieved", [])]
            == [c["text"] for c in row["retrieved"]]
        )
        if same and any(old["labels"].get(key) is not None for key in ("refused", "fabricated")):
            row["labels"] = old["labels"]
            kept.append(row["question"])
        else:
            stale.append(row["question"])
    return kept, stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing file, discarding the hand labels in it",
    )
    parser.add_argument(
        "--set",
        choices=("refusal", "answerable"),
        default="refusal",
        help="which population to record: the refusal questions, or the 26 "
        "answerable ones that RAGAS and DeepEval score",
    )
    parser.add_argument(
        "--keep-labels",
        action="store_true",
        help="carry hand labels onto records whose answer and chunks came out "
        "byte-identical, and report which ones need labelling again",
    )
    parser.add_argument(
        "--out",
        type=pathlib.Path,
        help="write somewhere other than the canonical file - for recording a "
        "second set beside a labelled one instead of over it",
    )
    parser.add_argument(
        "--labels-from",
        type=pathlib.Path,
        help="with --keep-labels, the file to carry labels from. Defaults to "
        "the file being written; point it at the old set when recording beside it",
    )
    args = parser.parse_args()
    if args.keep_labels and args.set != "refusal":
        raise SystemExit("--keep-labels applies to the refusal set; it is the only labelled one")

    refusal = args.set == "refusal"
    out = args.out or (OUT if refusal else ANSWERABLE_OUT)

    if out.exists() and not args.force:
        raise SystemExit(
            f"{out} already exists and the numbers in the README describe it.\n"
            "Regenerating replaces the answers every cached score was computed\n"
            "from. Pass --force only if you mean to discard them."
        )

    records = refusal_records() if refusal else answerable_records()
    print(f"recording {len(records)} answers - one model call each\n")
    rows = build(records, refusal=refusal)

    kept, stale = [], []
    if args.keep_labels:
        kept, stale = carry_labels(rows, args.labels_from or out)

    header = (HEADER if refusal else ANSWERABLE_HEADER).format(
        recorded=datetime.datetime.now(tz=datetime.UTC).date().isoformat(),
        model=pipeline.MODEL,
        options={"temperature": 0, "seed": 0},
        retriever=pipeline.RETRIEVE.__name__,
        k=pipeline.K,
        embedder=store.EMBEDDER.__class__.__name__ + " all-MiniLM-L6-v2",
        size=chunker.SIZE,
        overlap=chunker.OVERLAP,
    )
    body = yaml.dump(
        rows, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=88
    )
    out.write_text(header + "\n" + body, encoding="utf-8")

    print(f"\nwrote {out} - {len(rows)} records")
    if args.keep_labels:
        print(f"labels carried over: {len(kept)}; need labelling again: {len(stale)}")
        for question in stale:
            print(f"  - {question[:70]}")
        print(
            "\nA label describes one answer against the chunks it was written from.\n"
            "Where either changed, the old verdict is about text that no longer\n"
            "exists, and the judge verdicts cached for those records miss too."
        )
    if refusal:
        print("\nuv run python scripts/label_refusals.py")
    else:
        print("Now: uv run python scripts/ragas_eval.py")


if __name__ == "__main__":
    main()
